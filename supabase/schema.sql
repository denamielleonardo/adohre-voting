-- Dashboard data for one poll. results (positions with vote counts) is null while the poll is
-- Active, unless show_live_results is on.
create or replace function public.admin_poll_dashboard(p_id int)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_poll public.polls;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  select * into v_poll from public.polls where id = p_id;
  if not found then raise exception 'Poll not found'; end if;

  return jsonb_build_object(
    'id', v_poll.id,
    'title', v_poll.title,
    'description', v_poll.description,
    'kind', v_poll.kind,
    'status', v_poll.status,
    'show_live_results', v_poll.show_live_results,
    'present', (select count(*) from public.attendance where revoked_at is null),
    'voted', (select count(*) from public.votes_cast where poll_id = p_id),
    'results', case
      when v_poll.status = 'open' and not v_poll.show_live_results then null
      else public.poll_positions_json(p_id, true)
    end
  );
end;
$$;

