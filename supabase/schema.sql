-- ---------------------------------------------------------------------------
-- Voter identity (QR + the email/phone staff entered -> session token)
-- ---------------------------------------------------------------------------
-- Internal: the voter (attendance id) behind a session token, or null if the token is unknown, the
-- voter's access was revoked, or the session is older than 24 hours (they scan and verify again).
create or replace function public.session_voter(p_session text)
returns bigint
language sql stable security definer set search_path = ''
as $$
  select s.voter_id
    from public.voter_sessions s
    join public.attendance a on a.id = s.voter_id and a.revoked_at is null
   where s.token_hash = encode(sha256(convert_to(coalesce(p_session, ''), 'utf8')), 'hex')
     and s.created_at > now() - interval '24 hours';
$$;

-- Step 2 of the voter flow. Returns { ok: true, session, name } or { ok: false, reason }.
-- reason: invalid (unknown QR) | revoked | locked (too many wrong tries) | mismatch (wrong email/number or password).
-- It returns instead of raising so the wrong-try counter is kept.
create or replace function public.voter_redeem(p_token text, p_identifier text, p_password text)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_att     public.attendance;
  v_ident   text := btrim(coalesce(p_identifier, ''));
  v_key     text;
  v_match   boolean;
  v_session text;
begin
  select * into v_att from public.attendance where qr_token = coalesce(p_token, '') for update;
  if not found then return jsonb_build_object('ok', false, 'reason', 'invalid'); end if;
  if v_att.revoked_at is not null then return jsonb_build_object('ok', false, 'reason', 'revoked'); end if;
  if v_att.locked_until is not null and v_att.locked_until > now() then
    return jsonb_build_object('ok', false, 'reason', 'locked');
  end if;

  if position('@' in v_ident) > 0 then
    v_match := lower(v_ident) = v_att.email_key;
  else
    v_key := nullif(right(regexp_replace(v_ident, '\D', '', 'g'), 10), '');
    v_match := v_key is not null and v_key = v_att.phone_key;
  end if;

  -- the password must match too (rows made before passwords existed have none: email/number only)
  if v_att.password_hash is not null then
    v_match := coalesce(v_match, false)
      and extensions.crypt(coalesce(p_password, ''), v_att.password_hash) = v_att.password_hash;
  end if;

  if not coalesce(v_match, false) then
    update public.attendance
       set locked_until    = case when failed_attempts >= 4 then now() + interval '15 minutes' else locked_until end,
           failed_attempts = case when failed_attempts >= 4 then 0 else failed_attempts + 1 end
     where id = v_att.id;
    return jsonb_build_object('ok', false, 'reason', 'mismatch');
  end if;

  update public.attendance set failed_attempts = 0, locked_until = null where id = v_att.id;

  -- sessions last 24 hours: tidy up expired ones whenever someone signs in
  delete from public.voter_sessions where created_at <= now() - interval '24 hours';

  v_session := replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', '');
  insert into public.voter_sessions (token_hash, voter_id)
    values (encode(sha256(convert_to(v_session, 'utf8')), 'hex'), v_att.id);
  -- keep only the 5 newest devices per voter
  delete from public.voter_sessions
   where voter_id = v_att.id
     and token_hash not in (select token_hash from public.voter_sessions
                             where voter_id = v_att.id order by created_at desc limit 5);

  return jsonb_build_object('ok', true, 'session', v_session,
    'name', coalesce(nullif(btrim(v_att.name), ''), v_att.email, v_att.phone));
end;
$$;

-- Who is signed in on this device. Raises when the session is gone or access was revoked.
create or replace function public.voter_me(p_session text)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_id  bigint := public.session_voter(p_session);
  v_att public.attendance;
begin
  if v_id is null then raise exception 'Your access has ended. Please see the registration desk.'; end if;
  select * into v_att from public.attendance where id = v_id;
  return jsonb_build_object('name', coalesce(nullif(btrim(v_att.name), ''), v_att.email, v_att.phone));
end;
$$;

create or replace function public.voter_sign_out(p_session text)
returns void
language sql security definer set search_path = ''
as $$
  delete from public.voter_sessions
   where token_hash = encode(sha256(convert_to(coalesce(p_session, ''), 'utf8')), 'hex');
$$;

