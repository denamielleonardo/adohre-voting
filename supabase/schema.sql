-- Voting system schema: attendance (the voters) + QR sign-in, polls with positions.
-- Run in the Supabase SQL Editor. Safe to re-run.
--
-- There is no separate voter list. Whoever staff record on the attendance form IS a voter:
--   1. Staff fill in the attendance form (name, email and/or cellphone number). The only check is
--      for duplicates (the same email or the same cellphone number already recorded).
--   2. A QR code unique to that attendee is made. The voter scans it, lands on the site, and types the
--      email OR cellphone number that staff entered. It must match this attendee. A session then starts
--      and lasts until they sign out or an admin revokes their access.
-- Admins sign in with an email and a password (Supabase Auth).
--
-- Upgrading: re-running this on an earlier layout converts it in place. The old member list
-- (allowed_voters) is folded into attendance: everyone with attendance keeps their record, QR and
-- sessions, and members who voted keep their "voted" marks. Members who never attended and never voted
-- are dropped with the old list. Polls, positions and ballots are untouched.

do $$
begin
  if to_regclass('public.candidates') is not null then
    drop table if exists public.ballots, public.candidates, public.positions, public.election cascade;
    drop function if exists public.get_ballot();
    drop function if exists public.get_turnout();
    drop function if exists public.get_results();
    drop function if exists public.cast_vote(jsonb);
  end if;
end $$;

create table if not exists public.admins (
  email text primary key check (email = lower(email))
);

-- ---------------------------------------------------------------------------
-- Attendance = the voters
-- ---------------------------------------------------------------------------
create table if not exists public.attendance (
  id              bigint generated by default as identity primary key,
  name            text,
  email           text,
  phone           text,
  qr_token        text not null unique default replace(gen_random_uuid()::text || gen_random_uuid()::text, '-', ''),
  recorded_by     text,
  recorded_at     timestamptz not null default now(),
  revoked_at      timestamptz,            -- set by an admin: ends access and logs the voter out
  failed_attempts int not null default 0, -- wrong email/number tries since the last success
  locked_until    timestamptz             -- set after 5 wrong tries
);
