-- ---------------------------------------------------------------------------
-- Polls
-- ---------------------------------------------------------------------------
-- A poll is either a question or an election:
--   question:   one position; voter picks 1 option (e.g. Yes / No / Abstain), or up to N if the admin allows multiple answers
--   candidates: an election with several positions (President, Vice President, Directors, ...),
--               each with up to 15 candidates and its own maximum votes per voter (up to 15)
create table if not exists public.polls (
  id                serial primary key,
  title             text not null check (length(btrim(title)) between 1 and 200),
  description       text check (length(description) <= 1000),
  kind              text not null check (kind in ('question', 'candidates')),
  -- draft = Not Active, open = Active, closed = Closed, cancelled = Cancelled (voided, final)
  status            text not null default 'draft' check (status in ('draft', 'open', 'closed', 'cancelled')),
  -- Live candidate tallies let an admin infer individual votes (watch a known voter sign in,
  -- see which count moves). Off by default: results appear when the poll is closed.
  show_live_results boolean not null default false,
  created_at        timestamptz not null default now()
);
alter table public.polls drop constraint if exists polls_status_check;
alter table public.polls add constraint polls_status_check
  check (status in ('draft', 'open', 'closed', 'cancelled'));
-- Several polls may be Active at once (older databases had a one-open-poll rule: drop it).
drop index if exists public.polls_one_open;

create table if not exists public.poll_options (
  id         serial primary key,
  poll_id    int  not null references public.polls(id) on delete cascade,
  label      text not null check (length(btrim(label)) between 1 and 200),
  sort_order int  not null default 0
);

-- A position within a poll (a question has exactly one; an election has several).
create table if not exists public.poll_positions (
  id         serial primary key,
  poll_id    int  not null references public.polls(id) on delete cascade,
  title      text not null check (length(btrim(title)) between 1 and 200),
  max_votes  int  not null default 1 check (max_votes between 1 and 15),
  sort_order int  not null default 0
);
alter table public.poll_options
  add column if not exists position_id int references public.poll_positions(id) on delete cascade;

-- Upgrade from the layout before positions: one position per poll, taking over its old max_votes.
do $$
begin
  if exists (select 1 from information_schema.columns
              where table_schema = 'public' and table_name = 'polls' and column_name = 'max_votes') then
    insert into public.poll_positions (poll_id, title, max_votes)
      select p.id, p.title, p.max_votes from public.polls p
       where not exists (select 1 from public.poll_positions x where x.poll_id = p.id);
    update public.poll_options o
       set position_id = (select min(x.id) from public.poll_positions x where x.poll_id = o.poll_id)
     where o.position_id is null;
    alter table public.polls drop column max_votes;
  end if;
end $$;
alter table public.poll_options alter column position_id set not null;

-- Who has voted in which poll (voter_id = attendance id). Holds no choice and no timestamp.
create table if not exists public.votes_cast (
  poll_id  int    not null references public.polls(id) on delete cascade,
  voter_id bigint not null references public.attendance(id),
  primary key (poll_id, voter_id)
);

-- Anonymous: no voter reference, no timestamp, random id (no insertion-order link).
create table if not exists public.ballots (
  id        uuid primary key default gen_random_uuid(),
  poll_id   int not null references public.polls(id) on delete cascade,
  option_id int not null references public.poll_options(id) on delete cascade
);

-- ---------------------------------------------------------------------------
-- Upgrade: fold the old member list (allowed_voters) into attendance, then drop it.
-- ---------------------------------------------------------------------------
do $$
declare
  r record;
begin
  if to_regclass('public.allowed_voters') is null then return; end if;

  -- (a) very old member lists were keyed by email: give them an id, a name and a phone column
  if not exists (select 1 from information_schema.columns
                  where table_schema = 'public' and table_name = 'allowed_voters' and column_name = 'id') then
    alter table public.allowed_voters drop constraint if exists allowed_voters_pkey;
    alter table public.allowed_voters add column id bigint generated by default as identity;
    alter table public.allowed_voters add primary key (id);
  end if;
  alter table public.allowed_voters add column if not exists name  text;
  alter table public.allowed_voters add column if not exists phone text;
  alter table public.allowed_voters add column if not exists email text;

  -- (b) votes recorded by email -> by member id
  if exists (select 1 from information_schema.columns
              where table_schema = 'public' and table_name = 'votes_cast' and column_name = 'email') then
    alter table public.votes_cast add column if not exists voter_id bigint;
    update public.votes_cast v
       set voter_id = (select a.id from public.allowed_voters a where lower(btrim(a.email)) = lower(btrim(v.email)));
    delete from public.votes_cast where voter_id is null;
    alter table public.votes_cast drop constraint if exists votes_cast_pkey;
    alter table public.votes_cast drop column email;
    alter table public.votes_cast alter column voter_id set not null;
    alter table public.votes_cast add primary key (poll_id, voter_id);
  end if;

  -- (c) temporary link from each attendance row to its old member
  alter table public.attendance add column if not exists voter_id bigint;
  update public.attendance a
     set name = m.name, email = m.email, phone = m.phone
    from public.allowed_voters m
   where m.id = a.voter_id;
  -- members who voted but have no attendance row keep their "voted" mark through a revoked record
  insert into public.attendance (voter_id, name, email, phone, revoked_at, recorded_by)
    select m.id, m.name, m.email, m.phone, now(), 'migration'
      from public.allowed_voters m
     where exists (select 1 from public.votes_cast c where c.voter_id = m.id)
       and not exists (select 1 from public.attendance a where a.voter_id = m.id);

  -- (d) detach everything from the member table, then re-point it at attendance ids
  for r in select conrelid::regclass as tbl, conname from pg_constraint
            where contype = 'f' and confrelid = 'public.allowed_voters'::regclass loop
    execute format('alter table %s drop constraint %I', r.tbl, r.conname);
  end loop;
  -- two steps through negative ids so ids that swap never collide on the primary key
  update public.votes_cast c set voter_id = -a.id from public.attendance a where a.voter_id = c.voter_id;
  update public.votes_cast set voter_id = -voter_id where voter_id < 0;
  update public.voter_sessions s set voter_id = -a.id from public.attendance a where a.voter_id = s.voter_id;
  update public.voter_sessions set voter_id = -voter_id where voter_id < 0;
  delete from public.voter_sessions where voter_id not in (select id from public.attendance);

  alter table public.attendance drop column voter_id;
  alter table public.votes_cast drop constraint if exists votes_cast_voter_id_fkey;
  alter table public.votes_cast
    add constraint votes_cast_voter_id_fkey foreign key (voter_id) references public.attendance(id);
  alter table public.voter_sessions drop constraint if exists voter_sessions_voter_id_fkey;
  alter table public.voter_sessions
    add constraint voter_sessions_voter_id_fkey foreign key (voter_id) references public.attendance(id) on delete cascade;

  drop table public.allowed_voters;
end $$;

