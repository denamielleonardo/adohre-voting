-- Create a poll, or edit a Not Active one.
-- p: { id?, title, description?, kind, show_live_results?,
--      positions: [ { title, max_votes, options: [text] } ] }
-- A question takes exactly one position (its title is the poll title); an election takes 1 to 20.
create or replace function public.admin_save_poll(p jsonb)
returns int
language plpgsql security definer set search_path = ''
as $$
declare
  v_id      int  := nullif(p ->> 'id', '')::int;
  v_kind    text := p ->> 'kind';
  v_title   text := btrim(coalesce(p ->> 'title', ''));
  v_desc    text := nullif(btrim(coalesce(p ->> 'description', '')), '');
  v_live    boolean := coalesce((p ->> 'show_live_results')::boolean, false);
  v_pos     jsonb := coalesce(p -> 'positions', '[]'::jsonb);
  v_npos    int;
  v_status  text;
  v_item    jsonb;
  v_i       int;
  v_ptitle  text;
  v_labels  text[];
  v_n       int;
  v_max     int;
  v_pid     int;
  v_noun    text;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  if v_kind is null or v_kind not in ('question', 'candidates') then
    raise exception 'Choose a poll type';
  end if;
  if v_title = '' then raise exception 'Enter a title'; end if;
  if jsonb_typeof(v_pos) <> 'array' then raise exception 'Positions must be a list'; end if;

  v_npos := jsonb_array_length(v_pos);
  if v_npos < 1 then raise exception 'Add at least one position'; end if;
  if v_kind = 'question' and v_npos <> 1 then raise exception 'A question has exactly one set of answers'; end if;
  if v_npos > 20 then raise exception 'An election can have at most 20 positions'; end if;
  if v_kind = 'candidates' and
     (select count(distinct lower(btrim(coalesce(e ->> 'title', '')))) from jsonb_array_elements(v_pos) e) <> v_npos then
    raise exception 'Position titles must be unique';
  end if;

  if v_id is null then
    insert into public.polls (title, description, kind, show_live_results)
      values (v_title, v_desc, v_kind, v_live)
      returning id into v_id;
  else
    select status into v_status from public.polls where id = v_id for update;
    if not found then raise exception 'Poll not found'; end if;
    if v_status <> 'draft' then raise exception 'Only Not Active polls can be edited'; end if;
    update public.polls
       set title = v_title, description = v_desc, kind = v_kind, show_live_results = v_live
     where id = v_id;
    delete from public.poll_positions where poll_id = v_id; -- cascades to its options
  end if;

  v_noun := case v_kind when 'question' then 'choices' else 'candidates' end;

  for v_item, v_i in
    select t.e, t.i::int from jsonb_array_elements(v_pos) with ordinality as t(e, i)
  loop
    v_ptitle := case when v_kind = 'question' then v_title
                     else btrim(coalesce(v_item ->> 'title', '')) end;
    if v_ptitle = '' then raise exception 'Position % needs a title', v_i; end if;

    select array_agg(btrim(x.l) order by x.i) into v_labels
      from jsonb_array_elements_text(coalesce(v_item -> 'options', '[]'::jsonb))
           with ordinality as x(l, i)
     where btrim(x.l) <> '';
    v_n := coalesce(cardinality(v_labels), 0);

    if v_kind = 'question' and v_n < 2 then
      raise exception 'A question needs at least 2 answer choices';
    end if;
    if v_kind = 'candidates' and v_n < 1 then
      raise exception '"%" needs at least 1 candidate', v_ptitle;
    end if;
    if v_n > 15 then
      raise exception '"%" can have at most 15 % (you have %)', v_ptitle, v_noun, v_n;
    end if;
    if (select count(distinct lower(x)) from unnest(v_labels) as x) <> v_n then
      raise exception '"%": options must be unique', v_ptitle;
    end if;

    v_max := coalesce((v_item ->> 'max_votes')::int, 1);
    if v_max < 1 or v_max > 15 then
      raise exception '"%": votes per voter must be between 1 and 15', v_ptitle;
    end if;
    if v_max > v_n then
      raise exception '"%": votes per voter (%) cannot exceed the number of % (%)', v_ptitle, v_max, v_noun, v_n;
    end if;

    insert into public.poll_positions (poll_id, title, max_votes, sort_order)
      values (v_id, v_ptitle, v_max, v_i)
      returning id into v_pid;
    insert into public.poll_options (poll_id, position_id, label, sort_order)
      select v_id, v_pid, x, i from unnest(v_labels) with ordinality as t(x, i);
  end loop;

  return v_id;
end;
$$;

-- Status changes:
--   Not Active (draft) -> Active (open)       activate
--   Active (open)      -> Closed              close
--   Closed             -> Active (open)       reopen
--   Active or Closed   -> Not Active (draft)  only while nobody has voted in it yet
--   any except Cancelled -> Cancelled         cancel (voids the poll; final)
create or replace function public.admin_set_poll_status(p_id int, p_status text)
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_cur text;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  select status into v_cur from public.polls where id = p_id for update;
  if not found then raise exception 'Poll not found'; end if;
  if v_cur = 'cancelled' then raise exception 'A cancelled poll cannot be changed'; end if;

  if p_status = 'open' then
    if v_cur = 'open' then return; end if;
    update public.polls set status = 'open' where id = p_id;
  elsif p_status = 'closed' then
    if v_cur <> 'open' then raise exception 'Only an Active poll can be closed'; end if;
    update public.polls set status = 'closed' where id = p_id;
  elsif p_status = 'draft' then
    if v_cur = 'draft' then return; end if;
    if exists (select 1 from public.votes_cast where poll_id = p_id) then
      raise exception 'Votes have already been cast, so this poll cannot be made Not Active. Close it instead.';
    end if;
    update public.polls set status = 'draft' where id = p_id;
  elsif p_status = 'cancelled' then
    update public.polls set status = 'cancelled' where id = p_id;
  else
    raise exception 'Invalid status';
  end if;
end;
$$;

-- Delete a poll with all its positions, options, ballots and participation records.
