-- Positions of a poll with their options (and vote counts when p_counts is true).
-- Internal helper: not callable from the browser (see grants at the end).
create or replace function public.poll_positions_json(p_poll_id int, p_counts boolean)
returns jsonb
language sql stable security definer set search_path = ''
as $$
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', pp.id,
    'title', pp.title,
    'max_votes', pp.max_votes,
    'options', (select coalesce(jsonb_agg(
                  case when p_counts
                    then jsonb_build_object('id', o.id, 'label', o.label,
                           'votes', (select count(*) from public.ballots b where b.option_id = o.id))
                    else jsonb_build_object('id', o.id, 'label', o.label)
                  end order by o.sort_order, o.id), '[]'::jsonb)
                from public.poll_options o where o.position_id = pp.id)
  ) order by pp.sort_order, pp.id), '[]'::jsonb)
  from public.poll_positions pp
  where pp.poll_id = p_poll_id;
$$;

-- Every Active poll for the signed-in voter, with whether they already voted in each.
create or replace function public.get_active_polls(p_session text)
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
declare
  v_id bigint := public.session_voter(p_session);
begin
  if v_id is null then raise exception 'Your access has ended. Please see the registration desk.'; end if;
  return (
    select coalesce(jsonb_agg(jsonb_build_object(
      'id', p.id,
      'title', p.title,
      'description', p.description,
      'kind', p.kind,
      'has_voted', exists (select 1 from public.votes_cast v
                            where v.poll_id = p.id and v.voter_id = v_id),
      'positions', public.poll_positions_json(p.id, false)
    ) order by p.id), '[]'::jsonb)
    from public.polls p
    where p.status = 'open'
  );
end;
$$;

-- Submit a vote: distinct options of an open poll, at least 1 overall, and for each position
-- no more than its max_votes. Once per voter per poll. A position may be left empty.
create or replace function public.cast_vote(p_session text, p_poll_id int, p_option_ids int[])
returns void
language plpgsql security definer set search_path = ''
as $$
declare
  v_id        bigint := public.session_voter(p_session);
  v_poll      public.polls;
  v_n         int;
  v_bad_title text;
  v_bad_max   int;
begin
  if v_id is null then
    raise exception 'Your access has ended. Please see the registration desk.';
  end if;

  select * into v_poll from public.polls where id = p_poll_id;
  if not found or v_poll.status <> 'open' then
    raise exception 'This poll is not open';
  end if;

  v_n := coalesce(array_length(p_option_ids, 1), 0);
  if v_n < 1 then
    raise exception 'Select at least one option';
  end if;
  if (select count(distinct x) from unnest(p_option_ids) as x) <> v_n then
    raise exception 'Duplicate selections';
  end if;
  if (select count(*) from public.poll_options
       where poll_id = p_poll_id and id = any (p_option_ids)) <> v_n then
    raise exception 'Invalid selection';
  end if;

  select pp.title, pp.max_votes into v_bad_title, v_bad_max
    from public.poll_options o
    join public.poll_positions pp on pp.id = o.position_id
   where o.id = any (p_option_ids)
   group by pp.id, pp.title, pp.max_votes
  having count(*) > pp.max_votes
   limit 1;
  if found then
    raise exception 'You can select at most % for "%"', v_bad_max, v_bad_title;
  end if;

  -- Atomic one-vote guard per poll: the primary key admits only one concurrent insert.
  insert into public.votes_cast (poll_id, voter_id) values (p_poll_id, v_id)
    on conflict do nothing;
  if not found then
    raise exception 'You have already voted in this poll';
  end if;

  insert into public.ballots (poll_id, option_id)
    select p_poll_id, x from unnest(p_option_ids) as x;
  -- Any exception above rolls back the votes_cast insert too.
end;
$$;

-- ---------------------------------------------------------------------------
-- Admin: attendance (the attendance form creates the voter)
-- ---------------------------------------------------------------------------
-- Record an attendee and create their QR token. The only check is for duplicates: an email or a
-- cellphone number that is already recorded. Returns
--   { ok: true,  attendance: { id, name, email, phone, qr_token } }
--   { ok: false, reason: 'duplicate', existing: { id, name, email, phone, matched } }
create or replace function public.admin_record_attendance(
  p_first text, p_middle text, p_last text, p_email text, p_phone text, p_password text)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_first  text := btrim(coalesce(p_first, ''));
  v_middle text := nullif(btrim(coalesce(p_middle, '')), '');
  v_last   text := btrim(coalesce(p_last, ''));
  v_name   text;
  v_email  text := nullif(btrim(coalesce(p_email, '')), '');
  v_digits text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  v_ekey   text := nullif(lower(btrim(coalesce(p_email, ''))), '');
  v_pkey   text := nullif(right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 10), '');
  v_dup    public.attendance;
  v_att    public.attendance;
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  if v_first = '' then raise exception 'Enter the first name.'; end if;
  if v_last = '' then raise exception 'Enter the last name.'; end if;
  -- display name: first name + middle initial + last name, e.g. Den Amiel C. Leonardo
  v_name := concat_ws(' ', v_first, case when v_middle is not null then upper(left(v_middle, 1)) || '.' end, v_last);
  if v_ekey is null and v_pkey is null then raise exception 'Enter an email address or a cellphone number.'; end if;
  if v_ekey is not null and v_ekey !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'That email address does not look right.';
  end if;
  if v_pkey is not null and length(v_digits) < 10 then
    raise exception 'Enter the full cellphone number (at least 10 digits).';
  end if;
  if length(coalesce(p_password, '')) < 8 then raise exception 'The password must be at least 8 characters.'; end if;

  begin
    select * into v_dup from public.attendance
     where (v_ekey is not null and email_key = v_ekey) or (v_pkey is not null and phone_key = v_pkey)
     order by id limit 1;
    if not found then
      insert into public.attendance (name, first_name, middle_name, last_name, email, phone, password_hash, recorded_by)
        values (v_name, v_first, v_middle, v_last, v_email, nullif(btrim(coalesce(p_phone, '')), ''),
                extensions.crypt(p_password, extensions.gen_salt('bf')), lower(auth.jwt() ->> 'email'))
        returning * into v_att;
      return jsonb_build_object('ok', true, 'attendance', jsonb_build_object(
        'id', v_att.id, 'name', v_att.name, 'email', v_att.email, 'phone', v_att.phone, 'qr_token', v_att.qr_token));
    end if;
  exception when unique_violation then
    -- two staff recorded the same person at the same moment: report the one that won
    select * into v_dup from public.attendance
     where (v_ekey is not null and email_key = v_ekey) or (v_pkey is not null and phone_key = v_pkey)
     order by id limit 1;
  end;

  return jsonb_build_object('ok', false, 'reason', 'duplicate', 'existing', jsonb_build_object(
    'id', v_dup.id, 'name', v_dup.name, 'email', v_dup.email, 'phone', v_dup.phone,
    'matched', case
      when v_ekey is not null and v_dup.email_key = v_ekey and v_pkey is not null and v_dup.phone_key = v_pkey then 'email and cellphone number'
      when v_ekey is not null and v_dup.email_key = v_ekey then 'email'
      else 'cellphone number' end));
end;
$$;

-- Everyone recorded, newest first, with their QR token and access state.
-- present = attendees whose access is active (not revoked).
create or replace function public.admin_list_attendance()
returns jsonb
language plpgsql stable security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  return jsonb_build_object(
    'present', (select count(*) from public.attendance where revoked_at is null),
    'revoked', (select count(*) from public.attendance where revoked_at is not null),
    'attendees', (select coalesce(jsonb_agg(jsonb_build_object(
        'id', t.id, 'name', t.name, 'first_name', t.first_name, 'middle_name', t.middle_name, 'last_name', t.last_name,
        'email', t.email, 'phone', t.phone, 'has_password', t.password_hash is not null,
        'qr_token', t.qr_token, 'recorded_at', t.recorded_at, 'recorded_by', t.recorded_by,
        'revoked', t.revoked_at is not null,
        'locked', t.locked_until is not null and t.locked_until > now(),
        'sessions', (select count(*) from public.voter_sessions s
                      where s.voter_id = t.id and s.created_at > now() - interval '24 hours'),
        'votes', (select count(*) from public.votes_cast v where v.voter_id = t.id)
      ) order by t.recorded_at desc), '[]'::jsonb)
      from public.attendance t)
  );
end;
$$;

-- Correct a recorded person's name, email or cellphone number. The QR code, password, access state and any
-- votes stay as they are. Returns { ok: true } or { ok: false, reason: 'duplicate' } when another
-- person already has that email or cellphone number.
create or replace function public.admin_update_attendance(
  p_id bigint, p_first text, p_middle text, p_last text, p_email text, p_phone text)
returns jsonb
language plpgsql security definer set search_path = ''
as $$
declare
  v_first  text := btrim(coalesce(p_first, ''));
  v_middle text := nullif(btrim(coalesce(p_middle, '')), '');
  v_last   text := btrim(coalesce(p_last, ''));
  v_digits text := regexp_replace(coalesce(p_phone, ''), '\D', '', 'g');
  v_ekey   text := nullif(lower(btrim(coalesce(p_email, ''))), '');
  v_pkey   text := nullif(right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 10), '');
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  if v_first = '' then raise exception 'Enter the first name.'; end if;
  if v_last = '' then raise exception 'Enter the last name.'; end if;
  if v_ekey is null and v_pkey is null then raise exception 'Enter an email address or a cellphone number.'; end if;
  if v_ekey is not null and v_ekey !~ '^[^@\s]+@[^@\s]+\.[^@\s]+$' then
    raise exception 'That email address does not look right.';
  end if;
  if v_pkey is not null and length(v_digits) < 10 then
    raise exception 'Enter the full cellphone number (at least 10 digits).';
  end if;
  perform 1 from public.attendance where id = p_id for update;
  if not found then raise exception 'Attendance record not found'; end if;
  if exists (select 1 from public.attendance
              where id <> p_id and ((v_ekey is not null and email_key = v_ekey) or (v_pkey is not null and phone_key = v_pkey))) then
    return jsonb_build_object('ok', false, 'reason', 'duplicate');
  end if;
  begin
    update public.attendance
       set name = concat_ws(' ', v_first, case when v_middle is not null then upper(left(v_middle, 1)) || '.' end, v_last),
           first_name = v_first, middle_name = v_middle, last_name = v_last,
           email = nullif(btrim(coalesce(p_email, '')), ''),
           phone = nullif(btrim(coalesce(p_phone, '')), '')
     where id = p_id;
  exception when unique_violation then
    return jsonb_build_object('ok', false, 'reason', 'duplicate');
  end;
  return jsonb_build_object('ok', true);
end;
$$;

-- Set a new password for a recorded person (also clears any lock). The old password stops working.
create or replace function public.admin_set_attendance_password(p_id bigint, p_password text)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  if length(coalesce(p_password, '')) < 8 then raise exception 'The password must be at least 8 characters.'; end if;
  perform 1 from public.attendance where id = p_id for update;
  if not found then raise exception 'Attendance record not found'; end if;
  update public.attendance
     set password_hash = extensions.crypt(p_password, extensions.gen_salt('bf')),
         failed_attempts = 0, locked_until = null
   where id = p_id;
end;
$$;

-- Revoke (p_active = false): the voter is logged out everywhere and cannot sign in again.
-- Restore (p_active = true): access works again with the same QR, and any lock is cleared.
create or replace function public.admin_set_attendance_access(p_id bigint, p_active boolean)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  perform 1 from public.attendance where id = p_id for update;
  if not found then raise exception 'Attendance record not found'; end if;
  if p_active then
    update public.attendance set revoked_at = null, failed_attempts = 0, locked_until = null where id = p_id;
  else
    update public.attendance set revoked_at = now() where id = p_id;
    delete from public.voter_sessions where voter_id = p_id;
  end if;
end;
$$;

-- Remove an attendee who has not voted (a mistaken entry): the QR stops working and they are logged
-- out. Someone who already voted cannot be removed (their vote would become unattributed and they
-- could be recorded again and vote twice): revoke their access instead.
create or replace function public.admin_remove_attendance(p_id bigint)
returns void
language plpgsql security definer set search_path = ''
as $$
begin
  if not public.is_admin() then raise exception 'Admins only'; end if;
  perform 1 from public.attendance where id = p_id for update;
  if not found then raise exception 'Attendance record not found'; end if;
  if exists (select 1 from public.votes_cast where voter_id = p_id) then
    raise exception 'This person has already voted, so their record cannot be removed. Use Revoke access instead.';
  end if;
  delete from public.voter_sessions where voter_id = p_id;
  delete from public.attendance where id = p_id;
end;
$$;

